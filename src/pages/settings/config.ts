/** Saqlangan tartib sahifaning eski default tartibi bilan (umumiy ustunlar bo'yicha) bir xilmi. */
export function isLegacyDefaultOrder(pageId: string, stored: string[]): boolean {
  const olds = LEGACY_DEFAULT_ORDERS[pageId];
  if (!olds) return false;
  return olds.some((old) => {
    const a = stored.filter((c) => old.includes(c));
    const b = old.filter((c) => stored.includes(c));
    return a.length === b.length && a.every((c, i) => c === b[i]);
  });
}
